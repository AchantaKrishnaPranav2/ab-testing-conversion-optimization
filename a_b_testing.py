"""### Data Cleaning & Auditing

First, I'll filter out mismatched group-landing page assignments.
"""

initial_rows = df.shape[0]

# Filter out users in 'control' group who landed on 'new_page'
df_cleaned = df[~((df['group'] == 'control') & (df['landing_page'] == 'new_page'))]

