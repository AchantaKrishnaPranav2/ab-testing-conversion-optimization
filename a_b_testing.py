"""### Statistical Hypothesis Testing

I will now run a two-sample z-test on conversion rates to check for statistical significance.
"""

import statsmodels.api as sm
from statsmodels.stats.proportion import proportions_ztest

# Calculate conversions and total users for control and treatment groups
conversion_counts = df_cleaned.groupby('group')['converted'].agg(['sum', 'count'])

control_converted = conversion_counts.loc['control', 'sum']
control_total = conversion_counts.loc['control', 'count']
treatment_converted = conversion_counts.loc['treatment', 'sum']
treatment_total = conversion_counts.loc['treatment', 'count']

# Perform two-sample z-test
count = np.array([treatment_converted, control_converted])
nobs = np.array([treatment_total, control_total])

z_stat, p_value = proportions_ztest(count, nobs, alternative='larger') # Alternative='larger' tests if treatment > control

print(f"Control Group: {control_converted} conversions out of {control_total} users ({control_converted/control_total:.2%} conversion rate)")
print(f"Treatment Group: {treatment_converted} conversions out of {treatment_total} users ({treatment_converted/treatment_total:.2%} conversion rate)")
print(f"\nZ-statistic: {z_stat:.4f}")
print(f"P-value: {p_value:.4f}")

alpha = 0.05
if p_value < alpha:
    print(f"\nWith a p-value of {p_value:.4f} (less than alpha={alpha}), we reject the null hypothesis.")
    print("There is a statistically significant difference in conversion rates, with the treatment group converting more.")
else:
    print(f"\nWith a p-value of {p_value:.4f} (greater than or equal to alpha={alpha}), we fail to reject the null hypothesis.")
    print("There is no statistically significant difference in conversion rates between the control and treatment groups.")

# Calculate 95% Confidence Interval for the difference in proportions
# For two proportions, the CI can be calculated using a separate function or manually
from statsmodels.stats.proportion import confint_proportions_2indep

# Default method is 'wald', but 'agresti_coull' or 'jeffreys' might be more robust for small counts
conf_int_lower, conf_int_upper = confint_proportions_2indep(
    count[0], nobs[0], count[1], nobs[1],
    method='wald',
    compare='diff'
)

print(f"\n95% Confidence Interval for the difference in conversion rates (Treatment - Control): ({conf_int_lower:.4f}, {conf_int_upper:.4f})")

"""### Chi-Square Test of Independence for Sample Ratio Mismatch (SRM)

To ensure the randomization process was successful, I will perform a Chi-Square Test of Independence to check for Sample Ratio Mismatch (SRM) across different `device_type` categories. This test will help verify if the distribution of users across device types is similar in both the control and treatment groups.
"""

from scipy.stats import chi2_contingency

# Create a contingency table of 'group' vs 'device_type'
contingency_table = pd.crosstab(df_cleaned['device_type'], df_cleaned['group'])

print("Contingency Table (Device Type vs. Group):")
display(contingency_table)

# Perform the Chi-Square Test
chi2, p_value_chi2, dof, expected = chi2_contingency(contingency_table)

print(f"\nChi-Square Statistic: {chi2:.4f}")
print(f"P-value: {p_value_chi2:.4f}")
print(f"Degrees of Freedom: {dof}")

alpha_chi2 = 0.05
if p_value_chi2 < alpha_chi2:
    print(f"\nWith a p-value of {p_value_chi2:.4f} (less than alpha={alpha_chi2}), we reject the null hypothesis.")
    print("There is a statistically significant difference in the distribution of device types between the groups, indicating potential Sample Ratio Mismatch (SRM).")
else:
    print(f"\nWith a p-value of {p_value_chi2:.4f} (greater than or equal to alpha={alpha_chi2}), we fail to reject the null hypothesis.")
    print("There is no statistically significant difference in the distribution of device types between the groups, suggesting no Sample Ratio Mismatch (SRM).")

