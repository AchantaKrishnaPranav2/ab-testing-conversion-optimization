"""### Auditing Duplicate `user_id` Entries

Next, I'll identify and resolve any duplicate `user_id` entries to ensure each user is counted once and correctly assigned to a single group and landing page.
"""

# Check for duplicate user_ids
duplicate_users = df_cleaned[df_cleaned.duplicated(subset=['user_id'], keep=False)]

print(f"Number of duplicate user_id entries: {len(duplicate_users)}")
print(f"Number of unique users with duplicate entries: {duplicate_users['user_id'].nunique()}")

if not duplicate_users.empty:
    # Display some of the duplicate entries to understand the overlap
    print("\nExamples of duplicate user entries:")
    display(duplicate_users.sort_values(by='user_id').head())

    # Resolve session-level overlap: For simplicity and to maintain experiment integrity,
    # we will keep only the first entry for users who have multiple sessions
    # but are in the same group and saw the same landing page.
    # More critically, we'll identify users who appeared in both groups (a violation)
    # and remove them. Given the dataset structure, we'll aim for one entry per user.

    # Identify users who are in both control and treatment groups
    users_in_both_groups = df_cleaned.groupby('user_id')['group'].nunique()
    users_to_remove = users_in_both_groups[users_in_both_groups > 1].index

    if not users_to_remove.empty:
        print(f"\nUsers found in both groups (to be removed): {len(users_to_remove)}")
        df_cleaned_unique_groups = df_cleaned[~df_cleaned['user_id'].isin(users_to_remove)]
    else:
        print("\nNo users found in both control and treatment groups.")
        df_cleaned_unique_groups = df_cleaned.copy()

    # For users remaining, if they have multiple entries within the same group,
    # we'll keep the first one (assuming the first interaction is the most relevant,
    # or simply to ensure unique user_id rows for analysis).
    df_final = df_cleaned_unique_groups.drop_duplicates(subset=['user_id'], keep='first')

    rows_removed_due_to_duplicates = df_cleaned.shape[0] - df_final.shape[0]
    print(f"\nNumber of rows removed due to duplicate user_ids or users in both groups: {rows_removed_due_to_duplicates}")

    # Update df_cleaned to df_final
    df_cleaned = df_final

